def get_text(lang: str, key: str, **kwargs) -> str:
    """獲取翻譯文本"""
    if lang not in LANGUAGES:
        lang = 'zh'  # 默認中文
    
    text = LANGUAGES[lang].get(key, key)
    
    # 替換參數
    if kwargs:
        try:
            text = text.format(**kwargs)
        except:
            pass
    
    return text
